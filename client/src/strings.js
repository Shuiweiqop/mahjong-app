// Translation tables and the pure lookup logic over them.
//
// Deliberately a .js file with no React and no DOM access, for two reasons: the
// tests can import these functions directly (node cannot load .jsx), and the
// tables stay usable from any context. Everything that needs React lives in
// i18n.jsx, which re-exports from here.


export const LANGS = { en: 'English', zh: '中文' };

// Interpolate {name}-style placeholders. An undefined value leaves the placeholder
// in place, which makes a missing argument easy to spot.
export function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
}

// Look up a key: the requested language first, then English, then the key itself.
// Returning the key rather than a blank keeps an untranslated string visible.
export function translate(lang, key, vars) {
  const table = STRINGS[lang] || STRINGS.en;
  const raw = table[key] ?? STRINGS.en[key] ?? key;
  return interpolate(raw, vars);
}

// Game name: use the translation if the table has game.<id>, otherwise the
// displayName the server sent. If someone adds a game and forgets the entry, the
// lobby still shows the server's name rather than a raw key.
export function gameName(t, id, fallback) {
  const key = `game.${id}`;
  const out = t(key);
  return out === key ? (fallback || id) : out;
}

// Server error code -> text in the current language. The server only sends codes
// (see the note at the top of server/server.js).
// A code may carry one argument after a colon ("auth.passwordTooShort:8"), which
// fills the {n} placeholder, keeping limits that live in server config out of the
// translation tables.
// An unknown code is returned as-is: an older server still sending prose won't
// render as a blank, and a code added without a matching entry stays visible so
// the gap gets noticed.
export function serverError(t, code) {
  if (!code) return '';
  const [name, arg] = String(code).split(':');
  const key = `err.${name}`;
  const out = t(key, arg === undefined ? undefined : { n: arg });
  return out === key ? String(code) : out;
}

