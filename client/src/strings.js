// Translate the engine's { name, fan, description } into the same shape for the
// current language. Chinese is returned unchanged (the engine already emits Chinese);
// English is looked up, and a yaku with no translation yet falls back to the Chinese
// original so the UI still works instead of going blank.
// Names such as "幺九刻 x3" carry a count suffix: the base name is looked up and the
// suffix is appended back unchanged.
export function yakuText(lang, y) {
  if (lang !== 'en') return y;
  const hit = YAKU_EN[y.name];
  if (hit) return { ...y, name: hit[0], description: hit[1] };
  const [base, ...rest] = y.name.split(' ');
  const baseHit = YAKU_EN[base];
  if (!baseHit) return y;
  return { ...y, name: `${baseHit[0]} ${rest.join(' ')}`.trim(), description: baseHit[1] };
}
